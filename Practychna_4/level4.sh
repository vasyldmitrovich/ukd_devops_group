#!/bin/bash

# Функція: просто виводить текст
check_user() {
  echo "Користувач: $USER"
}

# Перевірка умови (якщо аргумент порожній)
if [ -z "$1" ]; then
  echo "Помилка: Ви не ввели число!"
else
  # Якщо число більше 10
  if [ "$1" -gt 10 ]; then
    echo "Число $1 більше за 10"
  fi
fi

# Цикл: виводить числа від 1 до 5
echo "Лічильник:"
for i in {1..5}; do
  echo "Число: $i"
done

# Виклик функції
check_user
