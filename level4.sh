#!/bin/bash

# --- Функція (вимога рівня 4) ---
check_user() {
   echo "Поточний користувач: $USER"
}

# 1. Перевірка аргумента (if/else)
if [ -z "$1" ]; then
    echo "Помилка: Ви не передали аргумент (число)!"
else
    # Перевірка чи число > 10
    if [ "$1" -gt 10 ]; then
        echo "Число $1 більше за 10"
    else
        echo "Число $1 менше або дорівнює 10"
    fi
fi

# 2. Case (вимога рівня 4)
# Спробуй запустити скрипт з параметром start, stop або status
case "$2" in
    start)  echo "Сервіс запускається..." ;;
    stop)   echo "Сервіс зупиняється..." ;;
    status) echo "Сервіс працює нормально." ;;
    *)      echo "Додатковий статус не вказано (спробуйте start/stop)" ;;
esac

# 3. Цикл та Масив (вимога рівня 4)
SERVERS=("web1" "web2" "db1")
echo "Список серверів у масиві:"
for server in "${SERVERS[@]}"; do
    echo "- Обробка сервера: $server"
done

# Виклик функції
check_user

