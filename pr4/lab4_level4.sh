#!/bin/bash

# --- 1. ФУНКЦІЯ (Рівень 4) ---
# Функція — це іменований блок коду. Ми її оголошуємо один раз, а викликати можемо всюди.
pereviryty_korystuvacha() {
   echo "Поточний користувач системи: $USER"
}

# --- 2. ПЕРЕВІРКА АРГУМЕНТУ (if) ---
# Перевіряємо, чи передав користувач хоча б один параметр ($1).
# Флаг -z означає "якщо рядок порожній".
if [ -z "$1" ]; then
    echo "Помилка: Ви не надали жодного аргументу!"
    exit 1 # Код завершення 1 вказує на те, що сталася помилка
else
    # Перевіряємо, чи є перший аргумент числом більшим за 10
    # -gt означає "greater than" (більше ніж)
    if [ "$1" -gt 10 ]; then
        echo "Число $1 більше за 10."
    else
        echo "Число $1 менше або дорівнює 10."
    fi
fi

# --- 3. ВИБІР ДІЇ (case) ---
# Case зручно використовувати для створення командного меню.
# Перевіряємо другий аргумент ($2).
case "$2" in
    start)
        echo "Сервіс запускається... Зачекайте."
        ;;
    stop)
        echo "Сервіс зупиняється... Вимкнення завершено."
        ;;
    status)
        echo "Статус сервісу: Працює стабільно (OK)."
        ;;
    *)
        echo "Дія (start|stop|status) не вказана у другому аргументі."
        ;;
esac

# --- 4. ЦИКЛИ ТА МАСИВИ (for) ---
echo "--- Цикл: вивід чисел від 1 до 5 ---"
for i in {1..5}; do
    echo "Крок №$i"
done

# Оголошуємо масив серверів
SERVERS=("web1" "web2" "db1")

echo "--- Цикл: прохід по масиву серверів ---"
# Спеціальний вираз "${SERVERS[@]}" дозволяє отримати всі елементи масиву
for server in "${SERVERS[@]}"; do
    echo "Спроба підключення до сервера: $server..."
done

# Викликаємо нашу функцію, яку ми створили на початку
pereviryty_korystuvacha
